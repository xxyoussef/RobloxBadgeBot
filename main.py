class BadgeBot(commands.Bot):
    def __init__(self):
        intents = discord.Intents.default()
        super().__init__(command_prefix="!", intents=intents)

    async def setup_hook(self):
        await self.tree.sync()
        print("Slash commands synced successfully!")

bot = BadgeBot()

@bot.event
async def on_ready():
    print(f"Logged in as {bot.user} (ID: {bot.user.id})")


@bot.tree.command(name="badges", description="Generate a cumulative badge graph for a Roblox user.")
@app_commands.describe(username="The Roblox username to inspect")
async def badges(interaction: discord.Interaction, username: str):
    await interaction.response.defer(thinking=True)

    try:
        buffer, count, user_id = await asyncio.to_thread(process_roblox_user, username)

        file = discord.File(fp=buffer, filename=f"{username}_badges.png")

        embed = discord.Embed(
            title=f"Badge History — {username}",
            description=f"**User ID:** {user_id}\n**Total Badges Tracked:** {count:,}",
            color=discord.Color.blue()
        )
        embed.set_image(url=f"attachment://{username}_badges.png")

        await interaction.followup.send(embed=embed, file=file)

    except PermissionError as pe:
        await interaction.followup.send(content=f"🔒 {str(pe)}")
    except ValueError as ve:
        await interaction.followup.send(content=f"⚠️ {str(ve)}")
    except Exception as e:
        await interaction.followup.send(content=f"❌ An error occurred: `{str(e)}`")


if __name__ == "__main__":
    bot.run(DISCORD_TOKEN)